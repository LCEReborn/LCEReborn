#!/usr/bin/env python3
"""Compile shaders offline and embed SPIR-V so installed games need no compiler or shader paths."""
import argparse
import pathlib
import re
import struct
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generator", required=True)
    parser.add_argument("--compiler", required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()
    directory = args.output.parent / "shaders"
    directory.mkdir(parents=True, exist_ok=True)
    for pattern in ("*.vert", "*.frag", "*.spv"):
        for path in directory.glob(pattern):
            path.unlink()
    subprocess.run([args.generator, str(directory)], check=True)
    header = ["// Generated by tools/build/spirv.py; do not edit.", "#include <cstddef>", "#include <cstdint>",
              "struct LceSpirvShader { const uint32_t* words; size_t size; unsigned samplers, uniforms; };"]
    for prefix, stage in (("v", "vert"), ("p", "frag")):
        entries = []
        sources = sorted(directory.glob(f"{prefix}*.{stage}"), key=lambda p: int(p.stem[1:]))
        for path in sources:
            binary = path.with_suffix(".spv")
            subprocess.run([args.compiler, "--target-env=vulkan1.0", "-Werror", str(path), "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            header.append(f"static const uint32_t {path.stem}[] = {{")
            header.extend(",".join(f"0x{word:08x}" for word in words[i:i + 8]) + "," for i in range(0, len(words), 8))
            header.append("};")
            source = path.read_text()
            samplers = len(re.findall(r"uniform sampler2D", source))
            blocks = re.findall(r"layout\s*\(([^)]*)\)\s*uniform\s+\w+\s*\{", source)
            bindings = [int(re.search(r"binding\s*=\s*(\d+)", layout).group(1)) for layout in blocks]
            uniforms = max(bindings, default=-1) + 1
            entries.append(f"{{{path.stem}, sizeof({path.stem}), {samplers}, {uniforms}}}")
        name = "lceVertexShaders" if prefix == "v" else "lcePixelShaders"
        header.append(f"static const LceSpirvShader {name}[] = {{" + ",".join(entries) + "};")
    temporary = args.output.with_suffix(".tmp")
    temporary.write_text("\n".join(header) + "\n")
    temporary.replace(args.output)


if __name__ == "__main__":
    main()
